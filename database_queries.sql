-- =====================================================================
-- ПРОЕКТ: Анализ эффективности онлайн-поддержки клиентов (тикет-система)
-- СУБД: MySQL / phpMyAdmin
-- Таблица: support_tickets (20 колонок, 8297 строк)
-- =====================================================================

USE `Проект1`;

-- ---------------------------------------------------------------------
-- ЗАПРОС 1: Распределение статусов и бэклог (Общая эффективность)
-- Показывает долю закрытых/выполненных задач относительно общего бэклога
-- ---------------------------------------------------------------------
SELECT 
    CASE 
        WHEN `Текущий статус` IN ('Закрыт', 'Выполнен') THEN 'Завершенные (Закрыт/Выполнен)'
        ELSE 'В работе / Другие'
    END AS `Группа статусов`,
    COUNT(*) AS `Количество тикетов`,
    ROUND(COUNT(*) * 100.0 / (SELECT COUNT(*) FROM `support_tickets`), 2) AS `Доля (%)`
FROM `support_tickets`
GROUP BY `Группа статусов`;


-- ---------------------------------------------------------------------
-- ЗАПРОС 2: Топ тематик обращений клиентов (Категории запросов)
-- Ранжирует проблемы клиентов по частоте возникновения для приоритизации
-- ---------------------------------------------------------------------
SELECT 
    `Категория 1` AS `Тематика`,
    COUNT(*) AS `Количество запросов`,
    ROUND(COUNT(*) * 100.0 / (SELECT COUNT(*) FROM `support_tickets`), 2) AS `Доля (%)`
FROM `support_tickets`
WHERE `Категория 1` IS NOT NULL
GROUP BY `Категория 1`
ORDER BY `Количество запросов` DESC;


-- ---------------------------------------------------------------------
-- ЗАПРОС 3: Матрица распределения тем по каналам связи (Сводный анализ)
-- Имитирует структуру тепловой карты (Heatmap) средствами SQL.
-- Позволяет понять, через какие мессенджеры чаще приходят конкретные боли.
-- ---------------------------------------------------------------------
SELECT 
    `Категория 1` AS `Тематика`,
    COUNT(CASE WHEN `Канал запроса` = 'Whatsap' THEN 1 END) AS `WhatsApp`,
    COUNT(CASE WHEN `Канал запроса` = 'чатбот - telegram' THEN 1 END) AS `Telegram`,
    COUNT(CASE WHEN `Канал запроса` = 'facebook' THEN 1 END) AS `Facebook`,
    COUNT(CASE WHEN `Канал запроса` = 'instagram' THEN 1 END) AS `Instagram`,
    COUNT(CASE WHEN `Канал запроса` = 'vk' THEN 1 END) AS `VK`
FROM `support_tickets`
WHERE `Категория 1` IS NOT NULL
GROUP BY `Категория 1`
ORDER BY `WhatsApp` DESC;
